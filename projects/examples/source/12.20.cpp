#include <cassert>
#include <iterator>
#include <string_view>

////////////////////////////////////////////////////////////////////////

using namespace std::literals;

////////////////////////////////////////////////////////////////////////

#include <boost/spirit/home/x3.hpp>

////////////////////////////////////////////////////////////////////////

int main()
{
    auto view = "1"sv;

//  --------------------------------------------------------------------

    auto rule = boost::spirit::x3::int_;

//  --------------------------------------------------------------------

    auto x = 0;

//  --------------------------------------------------------------------

    boost::spirit::x3::parse(std::begin(view), std::end(view), rule, x);

//  --------------------------------------------------------------------

    assert(x == 1);
}

