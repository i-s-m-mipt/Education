#include "06.09.hpp"

//////////////////////////////////////////////////////////////////////////

class Entity::Implementation
{
public :

    void test() const
    {
        std::print("Entity::Implementation::test\n");
    }
};

//////////////////////////////////////////////////////////////////////////

Entity::Entity() : m_implementation(new Implementation) {}

//////////////////////////////////////////////////////////////////////////

Entity::Entity(Entity && other) : m_implementation(other.m_implementation)
{
    other.m_implementation = nullptr;
}

//////////////////////////////////////////////////////////////////////////

Entity::~Entity()
{
    delete m_implementation;
}

//////////////////////////////////////////////////////////////////////////

auto & Entity::operator=(Entity && other)
{
    delete m_implementation;

    m_implementation = std::exchange(other.m_implementation, nullptr);

    return *this;
}

//////////////////////////////////////////////////////////////////////////

void Entity::test() const
{
    m_implementation->test();
}

