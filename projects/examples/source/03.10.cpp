#include <print>

////////////////////////////////////////////////////////////////////

class Key_v1 { private : friend class Client; Key_v1() = default; };

class Key_v2 { private :                      Key_v2() = default; };

////////////////////////////////////////////////////////////////////

class Server
{
private :

    friend class Client;

//  --------------------------------------------------------------

    static void test(Key_v1) { std::print("Server::test (1)\n"); }

    static void test(Key_v2) { std::print("Server::test (2)\n"); }
};

////////////////////////////////////////////////////////////////////

class Client
{
public :

    static void test()
    {
        Server::test(Key_v1());

    //  Server::test(Key_v2()); // error
    }
};

////////////////////////////////////////////////////////////////////

int main()
{
    Client::test();
}

