#include <boost/noncopyable.hpp>

//////////////////////////////////////////////////////////////////

template < typename T > class Wrapper : private boost::noncopyable
{
public :

	Wrapper(T x) : m_x(new T(x)) {}

//  -------------------------------

   ~Wrapper()
	{
		delete m_x;
	}

private :

	T * m_x = nullptr;
};

//////////////////////////////////////////////////////////////////

int main()
{
    Wrapper < int > wrapper(1);
}

