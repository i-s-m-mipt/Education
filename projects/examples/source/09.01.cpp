#include <boost/noncopyable.hpp>

//////////////////////////////////////////////////////////////////

template < typename T > class Entity : private boost::noncopyable
{
public :

	Entity(T x) : m_x(new T(x)) {}

//  ------------------------------

   ~Entity()
	{
		delete m_x;
	}

private :

	T * m_x = nullptr;
};

//////////////////////////////////////////////////////////////////

int main()
{
    Entity < int > entity(1);
}

